export type TKey = keyof typeof ru;
export const DICTS: Record<UiLang, typeof ru> = { ru, en };

export function translate(lang: UiLang, key: TKey, vars?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? DICTS.ru[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export interface I18n {
  lang: UiLang;
  t: (key: TKey, vars?: Record<string, string | number>) => string;
  m: (msg: Msg | null | undefined) => string;
  date: (iso: string | null | undefined, withTime?: boolean) => string;
  setLang: (l: UiLang) => void;
}

export const I18nContext = createContext<I18n>(null as any);
export const useI18n = () => useContext(I18nContext);

export function makeI18n(lang: UiLang, setLang: (l: UiLang) => void): I18n {
  const locale = lang === "ru" ? "ru-RU" : "en-GB";
  return {
    lang,
    setLang,
    t: (key, vars) => translate(lang, key, vars),
    m: (x) => (x ? x[lang] ?? x.ru : ""),
    date: (iso, withTime = false) => {
      if (!iso) return "—";
      const d = new Date(iso);
      if (Number.isNaN(d.getTime())) return iso;
      return d.toLocaleString(locale, withTime ? { day: "2-digit", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit" } : { day: "2-digit", month: "short", year: "numeric" });
    },
  };
}
