import { _electron as electron } from "playwright-core";
import fs from "node:fs"; import os from "node:os"; import path from "node:path";
const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), "jsd-peek-"));
const out = process.argv[2] || "/tmp/peek";
fs.mkdirSync(out, { recursive: true });
const app = await electron.launch({ args: ["."], env: { ...process.env, JSD_USER_DATA: dataDir } });
const win = await app.firstWindow();
const errors = [];
win.on("pageerror", (e) => errors.push(String(e)));
win.on("console", (m) => m.type() === "error" && errors.push(m.text()));
await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1280, 820));
await win.waitForTimeout(1500);
await win.screenshot({ path: `${out}/1-intro.png` });
await win.getByRole("button", { name: /Начать настройку|Start setup/ }).click();
await win.waitForTimeout(500);
await win.screenshot({ path: `${out}/2-about.png` });
console.log(JSON.stringify(errors));
await app.close(); fs.rmSync(dataDir, { recursive: true, force: true });
